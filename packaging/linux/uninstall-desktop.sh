#!/bin/sh
set -eu

directory=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
if [ "$(id -u)" = 0 ]; then
  echo 'Запустите деинсталлятор от обычного пользователя, без sudo.' >&2
  exit 1
fi
echo 'Сначала завершите FreeTurn через «Выйти из приложения» (не просто закройте окно).'
echo 'Будут удалены клиент, его ярлыки и автозапуск; доступ к VPN-helper будет отозван с подтверждением администратора.'
echo 'Профили, настройки и резервные копии обновлений сохраняются. Общий системный бинарник helper сохраняется для других пользователей.'
printf 'Приложение завершено. Удалить FreeTurn? [д/N]: '
answer=
IFS= read -r answer || :
case "$answer" in
  д|Д|да|Да|y|Y|yes|Yes) ;;
  *) echo 'Удаление отменено.'; exit 0 ;;
esac
"$directory/freeturn-desktop" --uninstall-desktop
echo 'FreeTurn удалён. Профили и резервные копии сохранены; распакованный архив можно удалить вручную.'
